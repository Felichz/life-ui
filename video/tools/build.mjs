/**
 * Assembles the film from its sources:
 * - assets/app.css: the app's built CSS (../dist), fonts pointed at assets/fonts.
 * - compositions/*.html: each scene in scenes/, with every `<!-- snap:NAME -->`
 *   replaced by the captured DOM in capture/NAME.html (ids stripped, so many
 *   captures can share one page).
 * Run `npm run build` in ../ first when the app changed, and the capture
 * (tools/capture.cy.ts) when its screens did.
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "..", "dist", "assets");

const cssFile = readdirSync(dist).find((name) => /^index-.*\.css$/.test(name));
if (!cssFile)
  throw new Error("No built CSS in ../dist/assets: run `npm run build` in the app first");
let css = readFileSync(join(dist, cssFile), "utf8");
// Only the Latin subsets are shipped with the film
css = css.replace(/@font-face\{[^}]*\}/g, (face) => {
  const latin = /inter-latin-wght-normal/.test(face)
    ? "inter-latin-wght-normal.woff2"
    : /inter-latin-ext-wght-normal/.test(face)
      ? "inter-latin-ext-wght-normal.woff2"
      : null;
  return latin ? face.replace(/url\([^)]*\)/, `url(fonts/${latin})`) : "";
});
// The film drives every change from its timeline: no CSS transitions or animations,
// which run on the browser clock and cannot be seeked
css = css
  .replace(/(^|[;{])\s*(transition|animation)(-[a-z-]+)?:[^;}]*;?/g, "$1")
  .replace(/@keyframes[^{]*\{(?:[^{}]*\{[^}]*\})*[^}]*\}/g, "");
// Monospace (code, kbd) falls back to a font the renderer bundles
css = css.replace(/font-family:\s*ui-monospace[^;}]*/g, 'font-family:"JetBrains Mono",monospace');
writeFileSync(join(root, "assets", "app.css"), css);

const snap = (name, extra) => {
  let html = readFileSync(join(root, "capture", `${name}.html`), "utf8");
  html = html.replace(/\s(id|aria-controls|aria-describedby|for)="[^"]*"/g, "");
  return `<div class="snap${extra ? ` ${extra}` : ""}" data-snap="${name}" data-layout-ignore>${html}</div>`;
};

// Where each scene aims, measured at capture time (a hidden scene can't measure itself)
const rects = readFileSync(join(root, "capture", "rects.json"), "utf8");
writeFileSync(join(root, "assets", "rects.js"), `window.RECTS = ${rects.trim()};\n`);

mkdirSync(join(root, "compositions"), { recursive: true });
for (const file of readdirSync(join(root, "scenes"))) {
  const source = readFileSync(join(root, "scenes", file), "utf8");
  const out = source.replace(/<!--\s*snap:([\w-]+)(?:\s+(\w+))?\s*-->/g, (_, name, extra) =>
    snap(name, extra)
  );
  writeFileSync(
    join(root, "compositions", file),
    `<!-- generated by tools/build.mjs from scenes/${file}: edit the source -->\n${out}`
  );
}
console.log(`app.css from ${cssFile}; scenes: ${readdirSync(join(root, "scenes")).join(", ")}`);
